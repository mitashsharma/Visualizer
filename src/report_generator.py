"""
report_generator.py

Generates downloadable PDF and HTML reports for the AI Data Visualizer.
"""

from pathlib import Path
from html import escape

from reportlab.lib.pagesizes import A4
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet


def _format_value(value):
    """Convert values into readable text."""

    if value is None:
        return "None"

    if isinstance(value, (list, tuple)):
        return ", ".join(str(item) for item in value)

    return str(value)


def generate_html_report(
    output_path,
    dataset_info=None,
    cleaning_summary=None,
    eda_results=None,
    visualizations=None,
    ml_results=None,
    ai_summary=None,
):
    """
    Generate an HTML report.

    Parameters
    ----------
    output_path : str or Path
        Location where the HTML report will be saved.

    dataset_info : dict, optional
        Basic dataset information.

    cleaning_summary : dict, optional
        Cleaning information.

    eda_results : dict, optional
        EDA results.

    visualizations : list, optional
        Visualization paths or descriptions.

    ml_results : dict, optional
        Machine learning results.

    ai_summary : dict, optional
        Summary generated by summarizer.py.

    Returns
    -------
    str
        Path of the generated HTML report.
    """

    output_path = Path(output_path)

    if output_path.suffix.lower() != ".html":
        output_path = output_path.with_suffix(".html")

    output_path.parent.mkdir(parents=True, exist_ok=True)

    sections = []

    sections.append(
        """
        <!DOCTYPE html>
        <html>
        <head>
            <meta charset="UTF-8">
            <title>AI Data Visualizer Report</title>
            <style>
                body {
                    font-family: Arial, sans-serif;
                    margin: 40px;
                    line-height: 1.6;
                    color: #222;
                }

                h1 {
                    margin-bottom: 5px;
                }

                h2 {
                    margin-top: 30px;
                    border-bottom: 1px solid #ddd;
                    padding-bottom: 5px;
                }

                .section {
                    margin-bottom: 25px;
                }

                ul {
                    padding-left: 25px;
                }

                table {
                    border-collapse: collapse;
                    width: 100%;
                }

                th, td {
                    border: 1px solid #ccc;
                    padding: 8px;
                    text-align: left;
                }

                th {
                    background-color: #f2f2f2;
                }
            </style>
        </head>
        <body>
            <h1>AI Data Visualizer Report</h1>
            <p>Automatically generated dataset analysis report.</p>
        """
    )

    # Dataset information
    if dataset_info:
        sections.append("<div class='section'>")
        sections.append("<h2>Dataset Information</h2>")
        sections.append("<ul>")

        for key, value in dataset_info.items():
            sections.append(
                f"<li><strong>{escape(str(key))}:</strong> "
                f"{escape(_format_value(value))}</li>"
            )

        sections.append("</ul>")
        sections.append("</div>")

    # Cleaning summary
    if cleaning_summary:
        sections.append("<div class='section'>")
        sections.append("<h2>Cleaning Summary</h2>")
        sections.append("<ul>")

        for key, value in cleaning_summary.items():
            sections.append(
                f"<li><strong>{escape(str(key))}:</strong> "
                f"{escape(_format_value(value))}</li>"
            )

        sections.append("</ul>")
        sections.append("</div>")

    # EDA results
    if eda_results:
        sections.append("<div class='section'>")
        sections.append("<h2>Exploratory Data Analysis</h2>")

        overview = eda_results.get("overview")

        if isinstance(overview, dict):
            sections.append("<h3>Overview</h3>")
            sections.append("<ul>")

            for key, value in overview.items():
                sections.append(
                    f"<li><strong>{escape(str(key))}:</strong> "
                    f"{escape(_format_value(value))}</li>"
                )

            sections.append("</ul>")

        insights = eda_results.get("insights")

        if isinstance(insights, list):
            sections.append("<h3>Insights</h3>")
            sections.append("<ul>")

            for insight in insights:
                sections.append(
                    f"<li>{escape(str(insight))}</li>"
                )

            sections.append("</ul>")

        sections.append("</div>")

    # Visualizations
    if visualizations:
        sections.append("<div class='section'>")
        sections.append("<h2>Visualizations</h2>")
        sections.append("<ul>")

        for visualization in visualizations:
            sections.append(
                f"<li>{escape(str(visualization))}</li>"
            )

        sections.append("</ul>")
        sections.append("</div>")

    # ML results
    if ml_results:
        sections.append("<div class='section'>")
        sections.append("<h2>Machine Learning Results</h2>")
        sections.append("<ul>")

        for key, value in ml_results.items():
            sections.append(
                f"<li><strong>{escape(str(key))}:</strong> "
                f"{escape(_format_value(value))}</li>"
            )

        sections.append("</ul>")
        sections.append("</div>")

    # AI summary
    if ai_summary:
        sections.append("<div class='section'>")
        sections.append("<h2>AI Summary</h2>")

        if isinstance(ai_summary, dict):

            for section_name, values in ai_summary.items():
                sections.append(
                    f"<h3>{escape(str(section_name))}</h3>"
                )

                if isinstance(values, list):
                    sections.append("<ul>")

                    for value in values:
                        sections.append(
                            f"<li>{escape(str(value))}</li>"
                        )

                    sections.append("</ul>")
                else:
                    sections.append(
                        f"<p>{escape(str(values))}</p>"
                    )

        else:
            sections.append(
                f"<p>{escape(str(ai_summary))}</p>"
            )

        sections.append("</div>")

    sections.append(
        """
        </body>
        </html>
        """
    )

    output_path.write_text(
        "".join(sections),
        encoding="utf-8",
    )

    return str(output_path)


def generate_pdf_report(
    output_path,
    dataset_info=None,
    cleaning_summary=None,
    eda_results=None,
    visualizations=None,
    ml_results=None,
    ai_summary=None,
):
    """
    Generate a PDF report.

    Parameters
    ----------
    output_path : str or Path
        Location where the PDF report will be saved.

    Returns
    -------
    str
        Path of the generated PDF report.
    """

    output_path = Path(output_path)

    if output_path.suffix.lower() != ".pdf":
        output_path = output_path.with_suffix(".pdf")

    output_path.parent.mkdir(parents=True, exist_ok=True)

    styles = getSampleStyleSheet()

    document = SimpleDocTemplate(
        str(output_path),
        pagesize=A4,
    )

    story = []

    story.append(
        Paragraph(
            "AI Data Visualizer Report",
            styles["Title"],
        )
    )

    story.append(
        Paragraph(
            "Automatically generated dataset analysis report.",
            styles["Normal"],
        )
    )

    story.append(Spacer(1, 15))

    def add_dictionary_section(title, data):
        if not data:
            return

        story.append(
            Paragraph(
                title,
                styles["Heading2"],
            )
        )

        table_data = [["Field", "Value"]]

        for key, value in data.items():
            table_data.append(
                [
                    str(key),
                    _format_value(value),
                ]
            )

        table = Table(table_data, repeatRows=1)

        table.setStyle(
            TableStyle(
                [
                    (
                        "BACKGROUND",
                        (0, 0),
                        (-1, 0),
                        colors.lightgrey,
                    ),
                    (
                        "GRID",
                        (0, 0),
                        (-1, -1),
                        0.5,
                        colors.grey,
                    ),
                    (
                        "VALIGN",
                        (0, 0),
                        (-1, -1),
                        "TOP",
                    ),
                    (
                        "PADDING",
                        (0, 0),
                        (-1, -1),
                        6,
                    ),
                ]
            )
        )

        story.append(table)
        story.append(Spacer(1, 12))

    add_dictionary_section(
        "Dataset Information",
        dataset_info,
    )

    add_dictionary_section(
        "Cleaning Summary",
        cleaning_summary,
    )

    if eda_results:
        story.append(
            Paragraph(
                "Exploratory Data Analysis",
                styles["Heading2"],
            )
        )

        overview = eda_results.get("overview")

        if isinstance(overview, dict):
            add_dictionary_section(
                "EDA Overview",
                overview,
            )

        insights = eda_results.get("insights")

        if isinstance(insights, list):
            story.append(
                Paragraph(
                    "EDA Insights",
                    styles["Heading3"],
                )
            )

            for insight in insights:
                story.append(
                    Paragraph(
                        f"• {escape(str(insight))}",
                        styles["Normal"],
                    )
                )

            story.append(Spacer(1, 10))

    if visualizations:
        story.append(
            Paragraph(
                "Visualizations",
                styles["Heading2"],
            )
        )

        for visualization in visualizations:
            story.append(
                Paragraph(
                    f"• {escape(str(visualization))}",
                    styles["Normal"],
                )
            )

        story.append(Spacer(1, 10))

    add_dictionary_section(
        "Machine Learning Results",
        ml_results,
    )

    if ai_summary:
        story.append(
            Paragraph(
                "AI Summary",
                styles["Heading2"],
            )
        )

        if isinstance(ai_summary, dict):

            for section_name, values in ai_summary.items():
                story.append(
                    Paragraph(
                        str(section_name),
                        styles["Heading3"],
                    )
                )

                if isinstance(values, list):
                    for value in values:
                        story.append(
                            Paragraph(
                                f"• {escape(str(value))}",
                                styles["Normal"],
                            )
                        )
                else:
                    story.append(
                        Paragraph(
                            escape(str(values)),
                            styles["Normal"],
                        )
                    )

        else:
            story.append(
                Paragraph(
                    escape(str(ai_summary)),
                    styles["Normal"],
                )
            )

    document.build(story)

    return str(output_path)